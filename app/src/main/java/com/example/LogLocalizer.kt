    fun format(lang: AppLanguage, key: LogKey, vararg args: Any): String {
        val t = if (lang == AppLanguage.AUTO) AppLanguage.detectSystemLanguage() else lang
        return when (t) {
            AppLanguage.ZH_TW -> formatZhTw(key, args)
            AppLanguage.ZH_CN -> formatZhCn(key, args)
            AppLanguage.EN -> formatEn(key, args)
            AppLanguage.JA -> formatJa(key, args)
            AppLanguage.KO -> formatKo(key, args)
            AppLanguage.ES -> formatEs(key, args)
            AppLanguage.FR -> formatFr(key, args)
            AppLanguage.DE -> formatDe(key, args)
            AppLanguage.RU -> formatRu(key, args)
            AppLanguage.PT -> formatPt(key, args)
            AppLanguage.AUTO -> formatEn(key, args)
        }
    }

    private fun reportIdModeName(lang: AppLanguage, modeName: String): String {
        val strings = StringProvider.get(lang)
        return when (modeName) {
            ReportIdMode.AUTO.name -> strings.reportIdAuto
            ReportIdMode.FORCE_1.name -> strings.reportIdForce1
            ReportIdMode.FORCE_0.name -> strings.reportIdForce0
            else -> modeName
        }
    }

    private fun hidProfileModeName(lang: AppLanguage, modeName: String): String {
        val strings = StringProvider.get(lang)
        return when (modeName) {
            HidProfileMode.COMBO.name -> strings.hidProfileCombo
            HidProfileMode.WACOM_PEN.name -> strings.hidProfileWacom
            HidProfileMode.KEYBOARD.name -> strings.hidProfileKeyboard
            HidProfileMode.MOUSE.name -> strings.hidProfileMouse
            else -> modeName
        }
    }

    private fun wacomOrientationName(lang: AppLanguage, orientName: String): String {
        val strings = StringProvider.get(lang)
        return when (orientName) {
            WacomOrientation.LANDSCAPE_0.name -> strings.orientLandscape0
            WacomOrientation.PORTRAIT_270_USB_TOP.name -> strings.orientPortrait270
            WacomOrientation.PORTRAIT_90.name -> strings.orientPortrait90
            WacomOrientation.LANDSCAPE_180.name -> strings.orientLandscape180
            else -> orientName
        }
    }

    private fun wacomPressureCurveName(lang: AppLanguage, curveName: String): String {
        val strings = StringProvider.get(lang)
        return when (curveName) {
            WacomPressureCurve.GAMMA_1_2.name -> strings.pressureGamma12
            WacomPressureCurve.LINEAR_1_0.name -> strings.pressureLinear
            else -> curveName
        }
    }

    private fun wacomButtonModeName(lang: AppLanguage, modeName: String): String {
        val strings = StringProvider.get(lang)
        return when (modeName) {
            WacomButtonMode.STYLUS_ONLY.name -> strings.btnModeStylusOnly
            WacomButtonMode.STYLUS_PLUS_SHORTCUTS.name -> strings.btnModeShortcuts
            else -> modeName
        }
    }

