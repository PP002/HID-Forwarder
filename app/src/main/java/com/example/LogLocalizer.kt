object LogLocalizer {
    private fun str(args: Array<out Any>, idx: Int): String =
        args.getOrNull(idx)?.toString() ?: ""

    private fun intArg(args: Array<out Any>, idx: Int): Int =
        (args.getOrNull(idx) as? Number)?.toInt() ?: 0

    private fun boolArg(args: Array<out Any>, idx: Int): Boolean =
        (args.getOrNull(idx) as? Boolean) ?: false

