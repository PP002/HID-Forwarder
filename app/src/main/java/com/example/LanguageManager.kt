enum class AppLanguage(
    val code: String,
    val displayName: String,
    val subName: String
) {
    AUTO("auto", "Auto (System)", "Device Language"),
    ZH_TW("zh-TW", "繁體中文", "Traditional Chinese"),
    ZH_CN("zh-CN", "简体中文", "Simplified Chinese"),
    EN("en", "English", "English (US/UK)"),
    JA("ja", "日本語", "Japanese"),
    KO("ko", "한국어", "Korean"),
    ES("es", "Español", "Spanish"),
    FR("fr", "Français", "French"),
    DE("de", "Deutsch", "German"),
    RU("ru", "Русский", "Russian"),
    PT("pt", "Português", "Portuguese");

    companion object {
        fun detectSystemLanguage(): AppLanguage {
            val locale = Locale.getDefault()
            val lang = locale.language.lowercase()
            val country = locale.country.uppercase()
            val script = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.LOLLIPOP) {
                locale.script.lowercase()
            } else {
                ""
            }

            return when {
                lang == "zh" -> {
                    if (script == "hant" || country in listOf("TW", "HK", "MO")) {
                        ZH_TW
                    } else {
                        ZH_CN
                    }
                }
                lang == "ja" -> JA
                lang == "ko" -> KO
                lang == "es" -> ES
                lang == "fr" -> FR
                lang == "de" -> DE
                lang == "ru" -> RU
                lang == "pt" -> PT
                lang == "en" -> EN
                else -> EN
            }
        }
    }
}

